// Generates src/lib/drawing/excalidrawFontFaces.ts: the font faces Excalidraw registers for
// its canvas (family → woff2 file + unicode-range), read from the package's own code. The
// static drawing preview is an inline SVG exported WITHOUT embedded fonts, so the document
// needs those faces itself (lib/drawing/drawingPreview.ts registers them, pointing at the
// self-hosted files — see the noteflow:excalidraw-fonts plugin in vite.config.ts).
//
// Run after upgrading @excalidraw/excalidraw:  node scripts/gen-excalidraw-font-faces.cjs
// tests/lib/excalidrawFontFaces.test.ts fails when the committed file is out of date.
const fs = require('fs')
const path = require('path')

const ROOT = path.resolve(__dirname, '..')
const DEV_DIR = path.join(ROOT, 'node_modules', '@excalidraw', 'excalidraw', 'dist', 'dev')
const OUT = path.join(ROOT, 'src', 'lib', 'drawing', 'excalidrawFontFaces.ts')
// Not shipped (CJK, 12.7 MB): its text falls back to a system font.
const SKIPPED_FAMILIES = new Set(['Xiaolai'])

function generate() {
  const chunk = fs.readdirSync(DEV_DIR)
    .filter((f) => /^chunk-.*\.js$/.test(f))
    .map((f) => fs.readFileSync(path.join(DEV_DIR, f), 'utf8'))
    .find((src) => src.includes('ASSETS_FALLBACK_URL') && src.includes('FontFaces = ['))
  if (!chunk) throw new Error('Excalidraw font registry not found in dist/dev')

  // var Foo_default = "./fonts/Dir/file.woff2";
  const uris = new Map()
  for (const m of chunk.matchAll(/^var (\w+) = "\.\/fonts\/([^"]+\.woff2)";$/gm)) uris.set(m[1], m[2])

  // var GOOGLE_FONTS_RANGES = { LATIN: "U+…", … };
  const googleRanges = new Map()
  const google = chunk.match(/^var GOOGLE_FONTS_RANGES = \{\n([\s\S]*?)\n\};$/m)
  for (const m of (google ? google[1] : '').matchAll(/(\w+):\s*"([^"]*)"/g)) googleRanges.set(m[1], m[2])

  // var XFontFaces = [ { uri: Foo_default, descriptors: { unicodeRange: "…" } }, … ];
  const lists = new Map()
  for (const m of chunk.matchAll(/^var (\w+FontFaces) = \[\n([\s\S]*?)\n\];$/gm)) {
    const faces = []
    for (const f of m[2].matchAll(/uri: (\w+)(?:,\s*descriptors: \{([^}]*)\})?/g)) {
      const file = uris.get(f[1])
      if (!file) continue // a local font (Helvetica, Segoe UI Emoji): nothing to load
      // descriptors: `unicodeRange: "U+…"` or `unicodeRange: GOOGLE_FONTS_RANGES.LATIN`, `weight: "500"`
      const face = { file, unicodeRange: null, weight: '400' }
      let rest = (f[2] ?? '').trim()
      for (const d of rest.matchAll(/(\w+):\s*(?:"([^"]*)"|GOOGLE_FONTS_RANGES\.(\w+))\s*,?/g)) {
        const value = d[2] ?? googleRanges.get(d[3])
        if (value === undefined || !(d[1] in face) || d[1] === 'file') throw new Error(`Unexpected font descriptor in ${m[1]}: ${d[0]}`)
        face[d[1]] = value
        rest = rest.replace(d[0], '')
      }
      if (rest.trim()) throw new Error(`Unexpected font descriptors in ${m[1]}: ${rest.trim()}`)
      faces.push(face)
    }
    lists.set(m[1], faces)
  }

  // init("Family", ...XFontFaces);
  const out = []
  for (const m of chunk.matchAll(/^\s*init\("([^"]+)", \.\.\.(\w+FontFaces)\);$/gm)) {
    if (SKIPPED_FAMILIES.has(m[1])) continue
    for (const face of lists.get(m[2]) ?? []) out.push({ family: m[1], ...face })
  }
  if (out.length === 0) throw new Error('No font faces found: the Excalidraw code changed shape')

  const version = JSON.parse(fs.readFileSync(path.join(DEV_DIR, '..', '..', 'package.json'), 'utf8')).version
  const rows = out.map((f) =>
    `  { family: ${JSON.stringify(f.family)}, file: ${JSON.stringify(f.file)}, weight: ${JSON.stringify(f.weight)}, unicodeRange: ${JSON.stringify(f.unicodeRange)} },`)
  return [
    `// GENERATED by scripts/gen-excalidraw-font-faces.cjs from @excalidraw/excalidraw ${version} — do not edit.`,
    '// The canvas font faces Excalidraw registers (Xiaolai left out): family, woff2 file under',
    '// `<EXCALIDRAW_ASSET_PATH>fonts/`, and the unicode-range of the subset (null = the whole font).',
    'export interface ExcalidrawFontFace {',
    '  family: string',
    '  file: string',
    '  weight: string',
    '  unicodeRange: string | null',
    '}',
    '',
    'export const EXCALIDRAW_FONT_FACES: readonly ExcalidrawFontFace[] = [',
    ...rows,
    ']',
    '',
  ].join('\n')
}

module.exports = { generate, OUT }

if (require.main === module) {
  fs.writeFileSync(OUT, generate())
  console.log(`Wrote ${path.relative(ROOT, OUT)}`)
}
